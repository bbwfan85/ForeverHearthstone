"""Pack-opening light (docs/19).

Original procedural artwork, white, tinted per rarity in the client
(SetVertexColor), drawn ADD behind a pack card:

  fx-aura   a soft glow in the card's own shape. The canvas is 1.5x the card
            (drawn 1.5x the card's rect, centred on it), so the light spills
            evenly round every edge; the card itself covers the middle.
  fx-rays   a sunburst of tapered light rays fading outward, spun behind an
            epic or legendary card as it turns over.

Output goes to ForeverHearthstone/Art as uncompressed TGA; provenance to
Art/pack-fx-report.json.
"""
from pathlib import Path
import json, math

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ForeverHearthstone" / "Art"
S = 2  # supersample
report = {}


def save(mask, name, size, note):
    im = Image.new("RGBA", mask.size, (255, 255, 255, 0))
    im.putalpha(mask)
    im = im.resize(size, Image.Resampling.LANCZOS)
    im.save(DEST / (name + ".tga"))
    report[name] = {"source": "generated by tools/build_pack_fx.py",
                    "provenance": "original procedural artwork", "texture_size": im.size,
                    "tint": "white; tinted in the client per rarity", "note": note}


# aura: card is 2/3 of the canvas each way; the glow starts a little inside
# the card's edge (hidden under it) and falls off softly well past it
W, H = 256 * S, 352 * S
cw, ch = W / 1.5, H / 1.5
x0, y0 = (W - cw) / 2, (H - ch) / 2
core = Image.new("L", (W, H), 0)
ImageDraw.Draw(core).rounded_rectangle((x0 + 4 * S, y0 + 4 * S, x0 + cw - 4 * S, y0 + ch - 4 * S),
                                       radius=16 * S, fill=255)
wide = core.filter(ImageFilter.GaussianBlur(26 * S))
tight = core.filter(ImageFilter.GaussianBlur(8 * S))
aura = ImageChops.lighter(wide.point(lambda v: min(255, int(v * 1.35))), tight.point(lambda v: int(v * 0.9)))
save(aura, "fx-aura", (256, 352), "draw at 1.5x the card's rect, centred")

# rays: 18 tapered rays of two lengths, radial falloff, soft edges
n = 256 * S
rays = Image.new("L", (n, n), 0)
d = ImageDraw.Draw(rays)
c = n / 2
count = 18
for k in range(count):
    a = k / count * math.tau
    length = (0.5 if k % 2 == 0 else 0.36) * n
    half = math.radians(2.6 if k % 2 == 0 else 1.8)
    tip = (c + math.cos(a) * length, c + math.sin(a) * length)
    l = (c + math.cos(a + half) * 10 * S, c + math.sin(a + half) * 10 * S)
    r = (c + math.cos(a - half) * 10 * S, c + math.sin(a - half) * 10 * S)
    d.polygon([l, tip, r, (c, c)], fill=255)
    # widen toward the middle of the ray
    mid = 0.45
    d.polygon([(c, c),
               (c + math.cos(a + half * 2.2) * length * mid, c + math.sin(a + half * 2.2) * length * mid),
               tip,
               (c + math.cos(a - half * 2.2) * length * mid, c + math.sin(a - half * 2.2) * length * mid)],
              fill=255)
rays = rays.filter(ImageFilter.GaussianBlur(3 * S))
fall = Image.new("L", (n, n), 0)
px = fall.load()
for y in range(n):
    for x in range(n):
        dd = math.hypot(x - c, y - c) / (n / 2)
        px[x, y] = int(255 * max(0.0, 1 - dd) ** 1.2)
rays = ImageChops.multiply(rays, fall)
glow = Image.new("L", (n, n), 0)
ImageDraw.Draw(glow).ellipse((c - 40 * S, c - 40 * S, c + 40 * S, c + 40 * S), fill=200)
glow = glow.filter(ImageFilter.GaussianBlur(24 * S))
save(ImageChops.lighter(rays, glow), "fx-rays", (256, 256), "spin slowly, fade out")

(DEST / "pack-fx-report.json").write_text(json.dumps(report, indent=2))
print("wrote", len(report), "textures")
