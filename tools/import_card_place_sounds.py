"""Import classic minion play recordings from Rymedy/hearthstone-web (docs/13).

HearthSFX, the card-audio source, lacks most 2014 minions (docs/11 §11.6), so
they land with Hearthstone's generic placement thud. Rymedy/hearthstone-web --
the source of the UI sounds already installed -- carries the PLAY line of about
two dozen classic minions (src/sounds/cardPlaceSnds). Each file is matched to a
card by its printed NAME (the file names are the names in snake case); a file
that matches no collectible minion, or a minion HearthSFX already covers, is
skipped rather than guessed. "_music_play" files are played alongside the voice
(Leeroy's and Alexstrasza's stings).

Output: Art/Sounds/Cards/rymedy_<name>.mp3, Client/Assets/CardPlaySounds.lua,
provenance in Art/card-place-sounds-report.json.
"""
from pathlib import Path
import hashlib, json, re, urllib.request

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / "ForeverHearthstone"
DEST = ADDON / "Art" / "Sounds" / "Cards"
BASE = "https://raw.githubusercontent.com/Rymedy/hearthstone-web/master/src/sounds/cardPlaceSnds/"
FILES = """acidic_swamp_ooze_play alexstrasza_music_play alexstrasza_play archmage_play
bloodfen_raptor_play boulderfist_ogre_play deathwing_play devout_adventurer_play
elite_tauren_chieftain_play elven_archer_play gnomish_inventor_play king_krush_play
leeroy_jenkins_music_play leeroy_jenkins_play lich_king_play lifedrinker_play
murloc_scout_play murloc_tidehunter_play ragnaros_the_firelord_play razorfen_hunter_play
saronite_chain_gang_play senjin_shieldmasta_play stormwind_champion_play voodoo_doctor_play""".split()


def slug(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower().replace("'", "")).strip("_")


def printed_minions():
    text = (ADDON / "Data" / "PrintedCards.lua").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r'P\["([^"]+)"\]=\{id="[^"]+",name="([^"]+)",type="MINION"[^\n]*collectible=true', text):
        out.setdefault(slug(m.group(2)), m.group(1))
    return out


def covered():
    text = (ADDON / "Client" / "Assets" / "CardSounds.lua").read_text(encoding="utf-8")
    return set(re.findall(r'\["([^"]+)"\]=\{summon=', text))


def main():
    minions, have = printed_minions(), covered()
    mapping, report = {}, {}
    for f in FILES:
        base = f[: -len("_music_play")] if f.endswith("_music_play") else f[: -len("_play")]
        card = minions.get(base)
        if not card:
            report[f] = {"skipped": "no collectible minion of that name in the pinned pool"}
            continue
        if card in have:
            report[f] = {"skipped": "HearthSFX already has this card", "card": card}
            continue
        dest = DEST / ("rymedy_" + f + ".mp3")
        url = BASE + f + ".mp3"
        if not dest.exists():
            req = urllib.request.Request(url, headers={"User-Agent": "ForeverHearthstone-local-import/1.0"})
            dest.write_bytes(urllib.request.urlopen(req, timeout=60).read())
        data = dest.read_bytes()
        mapping.setdefault(card, []).append(dest.name)
        report[f] = {"card": card, "source": url, "file": dest.name,
                     "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
    lines = ["-- Generated by tools/import_card_place_sounds.py from Rymedy/hearthstone-web.",
             "-- A minion's PLAY recording where HearthSFX has none. Provenance:",
             "-- Art/card-place-sounds-report.json.", "local _, ns = ...", "ns.CardPlaySounds = {"]
    for card in sorted(mapping):
        # the voice first, then any music sting
        files = sorted(mapping[card], key=lambda n: "_music_" in n)
        lines.append('  ["%s"]={%s},' % (card, ",".join(json.dumps(n) for n in files)))
    lines.append("}")
    (ADDON / "Client" / "Assets" / "CardPlaySounds.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ADDON / "Art" / "card-place-sounds-report.json").write_text(json.dumps(report, indent=2) + "\n")
    print("mapped", len(mapping), "minions;", sum(1 for r in report.values() if "skipped" in r), "skipped")


if __name__ == "__main__":
    main()
