"""The music button's icon (docs/21): music-on.tga / music-off.tga.

Original procedural artwork in the same hand as the speaker (mute-on/-off in
tools/build_match_assets.py, whose helpers are copied here so that script's
other textures are not regenerated): a dark disc in a gilded bevel, a cream
glyph -- two beamed eighth notes -- and, when the music is off, the same red
cross the muted speaker wears. Provenance: Art/music-icon-report.json.
"""
from pathlib import Path
import json

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ForeverHearthstone" / "Art"
GOLD_HI, GOLD_LO, BRONZE = (255, 238, 160), (150, 96, 30), (70, 42, 14)
S = 4
report = {}


def vgrad(size, top, bottom):
    w, h = size
    col = Image.new("RGBA", (1, h))
    for y in range(h):
        t = y / max(1, h - 1)
        col.putpixel((0, y), tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(4)))
    return col.resize(size)


def masked(fill, mask):
    out = fill.copy()
    out.putalpha(ImageChops.multiply(fill.getchannel("A"), mask))
    return out


def grow(mask, px): return mask.filter(ImageFilter.MaxFilter(px * 2 + 1))
def shrink(mask, px): return mask.filter(ImageFilter.MinFilter(px * 2 + 1))


def gilded(mask, size, rim=6):
    out = Image.new("RGBA", size)
    outline = ImageChops.subtract(grow(mask, 2), shrink(mask, rim))
    out.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (255,)), outline))
    ring = ImageChops.subtract(mask, shrink(mask, rim))
    out.alpha_composite(masked(vgrad(size, GOLD_HI + (255,), GOLD_LO + (255,)), ring))
    inner = ImageChops.subtract(shrink(mask, rim), shrink(mask, rim + 2))
    out.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (220,)), inner))
    return out


for state in ("on", "off"):
    size = (64 * S, 64 * S)
    im = Image.new("RGBA", size)
    disc = Image.new("L", size, 0)
    ImageDraw.Draw(disc).ellipse((4 * S, 4 * S, 60 * S, 60 * S), fill=255)
    im.alpha_composite(masked(vgrad(size, (70, 50, 34, 255), (26, 18, 12, 255)), disc))
    im.alpha_composite(gilded(disc, size, 4 * S))
    # two eighth notes on a slanted beam, heads bottom-left of each stem
    glyph = Image.new("L", size, 0)
    d = ImageDraw.Draw(glyph)
    shift = -7 if state == "off" else 0          # leave room for the cross
    x1, x2 = (26 + shift) * S, (42 + shift) * S  # stems' right edges
    y1, y2 = 18 * S, 15 * S                      # stem tops (the beam slants up)
    for x, top, bottom in ((x1, y1, 43 * S), (x2, y2, 40 * S)):
        d.rectangle((x - 3 * S, top, x, bottom), fill=255)
        d.ellipse((x - 11 * S, bottom - 5 * S, x + 1 * S, bottom + 4 * S), fill=255)
    d.polygon([(x1 - 3 * S, y1), (x2, y2), (x2, y2 + 6 * S), (x1 - 3 * S, y1 + 6 * S)], fill=255)
    cream = Image.new("RGBA", size, (255, 244, 214, 255))
    im.alpha_composite(masked(cream, glyph))
    if state == "off":
        marks = Image.new("L", size, 0)
        dm = ImageDraw.Draw(marks)
        dm.line([(42 * S, 32 * S), (53 * S, 47 * S)], fill=255, width=4 * S)
        dm.line([(53 * S, 32 * S), (42 * S, 47 * S)], fill=255, width=4 * S)
        im.alpha_composite(masked(Image.new("RGBA", size, (230, 60, 40, 255)), marks))
    im = im.resize((64, 64), Image.Resampling.LANCZOS)
    im.save(DEST / ("music-" + state + ".tga"))
    report["music-" + state] = {"source": "generated by tools/build_music_icon.py",
                                "provenance": "original procedural artwork", "texture_size": [64, 64]}

(DEST / "music-icon-report.json").write_text(json.dumps(report, indent=2))
print("wrote", len(report), "textures")
