"""Textures for the Hearthstone-style collection, deck and practice screens.

Run with the bundled Python + Pillow runtime (see docs/11). Two kinds of output:

* IMPORTED -- Hearthstone's class crests, as re-hosted by Manacost-Labs/HeartPulse
  (the source menu-parchment/menu-border already come from). Downloads are kept
  in tools/menu-assets so a rebuild does not need the network.
* GENERATED -- small procedural pieces with no source asset: the page-spine
  shade, the deck-list tile overlay and count box, the page-turn arrow, the
  Play button and a soft round glow. Drawn here, so they are original work.

Provenance and hashes: ForeverHearthstone/Art/hs-menus-report.json.
"""
from pathlib import Path
import hashlib, json, math, urllib.request

from PIL import Image, ImageDraw, ImageFilter, ImageChops

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "menu-assets"
DEST = ROOT / "ForeverHearthstone" / "Art"
HEARTPULSE = "https://raw.githubusercontent.com/Manacost-Labs/HeartPulse/main/public/class_icon/"
CRESTS = {c: c + ".png" for c in ("druid", "hunter", "mage", "paladin", "priest",
                                   "rogue", "shaman", "warlock", "warrior")}
CRESTS["all"] = "all1.png"
CRESTS["neutral"] = "neutral.webp"

report = {}


def save(im, name, provenance):
    im.save(DEST / (name + ".tga"))
    report[name] = dict(provenance, texture_size=im.size)


def fetch(file):
    path = SRC / ("class-" + file)
    if not path.exists():
        with urllib.request.urlopen(HEARTPULSE + file, timeout=30) as r:
            path.write_bytes(r.read())
    return path


# ------------------------------------------------------------------ imported

for key, file in CRESTS.items():
    path = fetch(file)
    im = Image.open(path).convert("RGBA").resize((128, 128), Image.Resampling.LANCZOS)
    save(im, "class-" + key, {"source": HEARTPULSE + file,
                              "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})

GENERATED = {"source": "generated by tools/build_hs_menus.py", "provenance": "original procedural artwork"}


def lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(len(a)))


def vgradient(size, top, bottom):
    w, h = size
    im = Image.new("RGBA", size)
    px = im.load()
    for y in range(h):
        c = lerp(top, bottom, y / max(1, h - 1))
        for x in range(w):
            px[x, y] = c
    return im


def rounded_mask(size, radius, inset=0):
    m = Image.new("L", size, 0)
    ImageDraw.Draw(m).rounded_rectangle((inset, inset, size[0] - 1 - inset, size[1] - 1 - inset),
                                        radius=radius, fill=255)
    return m


# The page spine: a shadow that falls off away from the fold. The client flips
# it with texture coordinates for the other page.
shade = Image.new("RGBA", (256, 64))
px = shade.load()
for x in range(256):
    a = round(150 * (1 - x / 255) ** 2.2)
    for y in range(64):
        px[x, y] = (40, 22, 8, a)
save(shade, "page-shade", GENERATED)

# A soft round glow, used behind the selected class crest and deck box.
glow = Image.new("RGBA", (128, 128))
px = glow.load()
for y in range(128):
    for x in range(128):
        d = math.hypot(x - 63.5, y - 63.5) / 64
        px[x, y] = (255, 255, 255, round(255 * max(0, 1 - d) ** 1.6))
save(glow, "crest-glow", GENERATED)

# Deck-list tile: a dark name plate that fades into the card's art strip on the
# right, inside a thin bronze rim -- the shape of Hearthstone's deck rows.
TW, TH = 512, 96
tile = Image.new("RGBA", (TW, TH))
px = tile.load()
for x in range(TW):
    t = x / (TW - 1)
    a = 250 if t < .34 else max(0, round(250 * (1 - (t - .34) / .30))) if t < .64 else 0
    for y in range(TH):
        edge = min(y, TH - 1 - y) / (TH / 2)
        dark = lerp((34, 24, 18), (14, 10, 8), 1 - edge)
        px[x, y] = dark + (a,)
rim = Image.new("RGBA", (TW, TH))
d = ImageDraw.Draw(rim)
d.rounded_rectangle((1, 1, TW - 2, TH - 2), radius=14, outline=(72, 46, 20, 255), width=7)
d.rounded_rectangle((3, 3, TW - 4, TH - 4), radius=12, outline=(196, 150, 78, 255), width=3)
d.rounded_rectangle((7, 7, TW - 8, TH - 8), radius=9, outline=(20, 12, 6, 200), width=2)
tile.putalpha(ImageChops.multiply(tile.getchannel("A"), rounded_mask((TW, TH), 14, 1)))
tile.alpha_composite(rim)
save(tile, "deck-tile", GENERATED)

# Count box on the tile's right end ("2", or a star for a legendary).
box = vgradient((64, 96), (40, 28, 18, 255), (12, 8, 6, 255))
box.putalpha(rounded_mask((64, 96), 10, 1))
d = ImageDraw.Draw(box)
d.rounded_rectangle((1, 1, 62, 94), radius=10, outline=(72, 46, 20, 255), width=5)
d.rounded_rectangle((3, 3, 60, 92), radius=8, outline=(214, 170, 90, 255), width=3)
save(box, "count-box", GENERATED)

# Page-turn arrow: a bevelled gold chevron with a dark outline, pointing right.
AW, AH = 128, 256
S = 4  # supersample
big = (AW * S, AH * S)
shape = [(18, 30), (70, 30), (118, 128), (70, 226), (18, 226), (62, 128)]
shape = [(x * S, y * S) for x, y in shape]
outline = Image.new("L", big, 0)
ImageDraw.Draw(outline).polygon(shape, fill=255)
outline = outline.filter(ImageFilter.MaxFilter(9 * S // 2 * 2 + 1))
body = Image.new("L", big, 0)
ImageDraw.Draw(body).polygon(shape, fill=255)
fill = vgradient(big, (255, 236, 150, 255), (176, 104, 26, 255))
highlight = vgradient(big, (255, 255, 230, 255), (255, 214, 110, 255))
inner = body.filter(ImageFilter.MinFilter(7 * S // 2 * 2 + 1))
arrow = Image.new("RGBA", big, (56, 30, 8, 0))
arrow.putalpha(outline)
arrow.alpha_composite(Image.composite(fill, Image.new("RGBA", big, (0, 0, 0, 0)), body))
arrow.alpha_composite(Image.composite(highlight, Image.new("RGBA", big, (0, 0, 0, 0)),
                                      ImageChops.subtract(body, inner).point(lambda v: v // 2)))
save(arrow.resize((AW, AH), Image.Resampling.LANCZOS), "page-arrow", GENERATED)

# The Play button is built from the tavern plaque by tools/build_play_button.py
# (docs/24); the generated amber pill that was here is no longer written.

(DEST / "hs-menus-report.json").write_text(json.dumps(report, indent=2))
print("wrote", len(report), "textures")
