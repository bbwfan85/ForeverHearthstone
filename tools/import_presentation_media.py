"""Import authentic UI textures and pinned-card audio; retain provenance."""
import ast, concurrent.futures, hashlib, io, json, re, urllib.request, wave
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
art=root/'ForeverHearthstone/Art'
report={"textures":{},"audio":{},"failed":[]}
prior=json.loads((art/"presentation-media-report.json").read_text()) if (art/"presentation-media-report.json").exists() else {}
failed={x["name"]:x["error"] for x in prior.get("failed",[])}
for name in ['hero_attack','hero_armor','inplay_minion_taunt','inplay_weapon','inplay_weapon_dome']:
    url=f'https://raw.githubusercontent.com/HearthSim/Joust/main/assets/images/{name}.png'
    data=urllib.request.urlopen(url,timeout=30).read()
    im=Image.open(io.BytesIO(data)).convert('RGBA')
    size=tuple(2**(v-1).bit_length() for v in im.size)
    im.resize(size,Image.Resampling.LANCZOS).save(art/(name+'.tga'))
    report['textures'][name]={"source":url,"sha256":hashlib.sha256(data).hexdigest()}
source=(root/'tools/hearthsfx-app.js').read_text(encoding='utf-8')
cards={}
for match in re.finditer(r"JSON\.parse\(('(?:\\.|[^'\\])*')\)",source):
    try: entries=json.loads(ast.literal_eval(match.group(1)))
    except (ValueError,SyntaxError): continue
    if isinstance(entries,list):
        for card in entries:
            if isinstance(card,dict) and 'id' in card and 'sounds' in card:
                cards[card['id']]=card
ids=re.findall(r'^P\["([^"]+)"\]',(root/'ForeverHearthstone/Data/PrintedCards.lua').read_text(),re.M)
mapping={}
variants={}
jobs={}
for id in ids:
    card=next((cards[key] for key in (id,'CORE_'+id,'VAN_'+id) if key in cards and cards[key]['sounds']),None)
    if not card: continue
    sounds={}
    for entry in card['sounds']:
        kind={'Play':'summon','Attack':'attack','Death':'death','Trigger':'trigger'}.get(entry['name'])
        layers=[]
        choices=[]
        for layer in entry.get('multi') or [entry]:
            audio=layer.get('audio')
            options=audio if isinstance(audio,list) else [audio]
            options=[name for name in options if isinstance(name,str) and re.fullmatch(r'[\w.-]+',name)]
            if options: layers.append(options[0]); choices.append(options)
        if kind and kind not in sounds and layers:
            sounds[kind]=layers
            variants.setdefault(id,{})[kind]=choices
            for options in choices:
                for name in options: jobs[name]=True
    if sounds: mapping[id]=sounds
generic={"impact":"Sword1_Attack_Underlay",
 "fire":"Fire_Underlay_Play","frost":"IceElemental_Underlay_Play",
 "holy":"HolyMagic_Play_Underlay","shadow":"ShadowMagic_Play_Underlay",
 "nature":"Nature_Magic_Underlay_Play","arcane":"ArcaneMagic_Play_Underlay",
 "weapon":"1H_SwordFine_Underlay_Play","arrow":"ArcaneFletcher_Bow_Underlay_Play"}
for name in generic.values(): jobs[name]=True
dest=art/'Sounds/Cards' ; dest.mkdir(parents=True,exist_ok=True)
def fetch(name):
    url='https://hearthstonesounds.s3.amazonaws.com/'+name+'.wav'
    path=dest/(name+'.wav')
    if name in failed and not path.exists(): return name,failed[name]
    try:
        data=path.read_bytes() if path.exists() else urllib.request.urlopen(url,timeout=30).read()
        with wave.open(io.BytesIO(data)) as w: params=w.getparams()
        path.write_bytes(data)
        return name,{"source":url,"sha256":hashlib.sha256(data).hexdigest(),"bytes":len(data),"channels":params.nchannels,"rate":params.framerate}
    except Exception as e: return name,str(e)
with concurrent.futures.ThreadPoolExecutor(max_workers=10) as pool:
    for name,result in pool.map(fetch,jobs):
        if isinstance(result,dict): report['audio'][name]=result
        else: report['failed'].append({"name":name,"error":result})
lines=['-- Generated by tools/import_presentation_media.py; HearthSFX card mappings.','local _, ns = ...','ns.CardSounds = {']
valid_variants={}
for id,sounds in sorted(mapping.items()):
    fields=[]
    for kind,names in sounds.items():
        layers=[[n for n in opts if n in report['audio']] for opts in variants[id][kind]]
        # A secondary underlay alone is not the card's complete event.
        if not layers or not layers[0]: continue
        layers=[opts for opts in layers if opts]
        fields.append(kind+'={'+','.join(json.dumps(opts[0]) for opts in layers)+'}')
        valid_variants.setdefault(id,{})[kind]=layers
    if fields: lines.append(f'  ["{id}"]={{'+','.join(fields)+'},')
lines.append('}')
lines.append('ns.CardSoundVariants = {')
for id,kinds in sorted(valid_variants.items()):
    fields=[]
    for kind,layers in kinds.items():
        fields.append(kind+'={'+','.join('{'+','.join(json.dumps(n) for n in opts)+'}' for opts in layers)+'}')
    lines.append(f'  ["{id}"]={{'+','.join(fields)+'},')
lines.append('}')
lines.append('ns.MatchRecordings = {')
for key,name in generic.items():
    if name in report['audio']: lines.append(f'  {key}="{name}",')
lines.append('}')
(root/'ForeverHearthstone/Client/Assets/CardSounds.lua').write_text('\n'.join(lines)+'\n')
(art/'presentation-media-report.json').write_text(json.dumps(report,indent=2))
print(f"Imported {len(report['textures'])} textures, {len(report['audio'])} audio files for {len(mapping)} cards; {len(report['failed'])} unavailable clips.")
