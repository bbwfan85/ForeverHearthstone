"""Measure the flat padding bands in the card art; write Client/Assets/ArtCrop.lua.

Run with the bundled Python + Pillow runtime after tools/fetch_art.py. About a
quarter of Hearthstone's square card art was padded out to square with flat
grey, white or black bands down the sides or across the top and bottom. Shown
whole, those bands are the grey sides of a card in hand or in the collection.

For each card-art texture this scans inward from each edge while a row or
column is (a) flat -- nearly one colour -- and (b) the same colour as the edge
itself, and records the art that remains as texture coordinates
{left, right, top, bottom}. Widgets.W.ArtCoords crops to it. Only cards that
actually have a band are written; the rest use the whole square.
"""
from pathlib import Path
import re

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "ForeverHearthstone" / "Art"
OUT = ROOT / "ForeverHearthstone" / "Client" / "Assets" / "ArtCrop.lua"
MANIFEST = ROOT / "ForeverHearthstone" / "Client" / "Assets" / "HearthstoneArt.lua"

FLAT = 7.0        # max std-dev (0-255) of a row/column to count as flat
SAME = 14.0       # max distance from the edge's colour
MAX_BAND = 0.30   # never crop more than this from one side
MIN_BAND = 3      # ignore bands thinner than this many pixels
INSET = 1         # one extra pixel past the band, to lose its soft edge


def band(lines):
    """lines: iterable of (N,3) arrays from the edge inward. Returns band width."""
    edge = None
    for i, line in enumerate(lines):
        if line.std(axis=0).max() > FLAT:
            return i
        colour = np.median(line, axis=0)
        if edge is None:
            edge = colour
        elif np.abs(colour - edge).max() > SAME:
            return i
    return len(lines)


def measure(path):
    px = np.asarray(Image.open(path).convert("RGB")).astype(np.float64)
    h, w, _ = px.shape
    cap_w, cap_h = int(w * MAX_BAND), int(h * MAX_BAND)
    left = band([px[:, x] for x in range(cap_w)])
    right = band([px[:, w - 1 - x] for x in range(cap_w)])
    top = band([px[y, :] for y in range(cap_h)])
    bottom = band([px[h - 1 - y, :] for y in range(cap_h)])
    sides = []
    for b, size in ((left, w), (right, w), (top, h), (bottom, h)):
        sides.append(0 if b < MIN_BAND else min(b + INSET, int(size * MAX_BAND)))
    if not any(sides):
        return None
    l, r, t, b = sides
    return (l / w, 1 - r / w, t / h, 1 - b / h)


def main():
    # Card art is every manifest key whose texture is a 256x256 illustration:
    # card ids, not frames, overlays, masks or boards.
    keys = re.findall(r'\["([^"]+)"\] = \[\[', MANIFEST.read_text(encoding="utf-8"))
    crops = {}
    for key in sorted(keys):
        path = ART / (key + ".tga")
        if not path.exists() or not re.match(r"^[A-Za-z]+[0-9]*[a-z]?_", key):
            continue
        if key.startswith(("inhand_", "inplay_", "board", "hero_", "secret_", "mask", "card-", "menu", "effect_", "icon_")):
            continue
        with Image.open(path) as im:
            if im.size != (256, 256):
                continue
        crop = measure(path)
        if crop:
            crops[key] = crop
    lines = ["-- Generated by tools/art_crop.py: the flat padding bands in the card art,",
             "-- as the {left, right, top, bottom} texture coordinates of what remains.",
             "-- Widgets.W.ArtCoords crops to these. Cards not listed have no band.",
             "local _, ns = ...", "ns.HearthstoneArtCrop = {"]
    for key, (l, r, t, b) in sorted(crops.items()):
        lines.append('  ["%s"] = { %.4f, %.4f, %.4f, %.4f },' % (key, l, r, t, b))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(crops)} card images have padding bands")


if __name__ == "__main__":
    main()
