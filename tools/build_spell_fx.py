"""Spell-effect shapes for the spell effects pass (docs/18).

Original procedural artwork, like tools/build_match_assets.py's fx-<school>
sprites -- but these three are WHITE and tinted by the client
(SetVertexColor with Client/FX/SpellFX.lua's school colour), so one texture
serves every school:

  fx-ring     a thin shockwave ring: impacts, novas, shields, a secret set
  fx-streak   a long tapered streak: slashes, knives, lightning segments,
              the head of a sweep
  fx-spark    a four-point sparkle: holy glints, frost glitter, buff motes

Output goes to ForeverHearthstone/Art as uncompressed TGA; provenance to
Art/spell-fx-report.json.
"""
from pathlib import Path
import json, math

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ForeverHearthstone" / "Art"
S = 4  # supersample
report = {}


def save(mask, name, size):
    im = Image.new("RGBA", mask.size, (255, 255, 255, 0))
    im.putalpha(mask)
    im = im.resize(size, Image.Resampling.LANCZOS)
    im.save(DEST / (name + ".tga"))
    report[name] = {"source": "generated by tools/build_spell_fx.py",
                    "provenance": "original procedural artwork", "texture_size": im.size,
                    "tint": "white; tinted in the client per spell school"}


# ring: a bright rim with a soft inner glow, empty centre
n = 128 * S
ring = Image.new("L", (n, n), 0)
d = ImageDraw.Draw(ring)
c = n / 2
d.ellipse((c - 58 * S, c - 58 * S, c + 58 * S, c + 58 * S), outline=255, width=7 * S)
ring = ring.filter(ImageFilter.GaussianBlur(3 * S))
halo = Image.new("L", (n, n), 0)
ImageDraw.Draw(halo).ellipse((c - 56 * S, c - 56 * S, c + 56 * S, c + 56 * S), outline=110, width=22 * S)
halo = halo.filter(ImageFilter.GaussianBlur(8 * S))
save(Image.composite(ring, halo, ring), "fx-ring", (128, 128))

# streak: horizontal, pointed at both ends, brightest just ahead of centre
w, h = 256 * S, 64 * S
streak = Image.new("L", (w, h), 0)
d = ImageDraw.Draw(streak)
cy = h / 2
d.polygon([(8 * S, cy), (150 * S, cy - 9 * S), (236 * S, cy - 3 * S), (250 * S, cy),
           (236 * S, cy + 3 * S), (150 * S, cy + 9 * S)], fill=255)
streak = streak.filter(ImageFilter.GaussianBlur(3 * S))
glow = Image.new("L", (w, h), 0)
ImageDraw.Draw(glow).ellipse((30 * S, cy - 22 * S, 246 * S, cy + 22 * S), fill=90)
glow = glow.filter(ImageFilter.GaussianBlur(10 * S))
save(Image.composite(streak, glow, streak), "fx-streak", (256, 64))

# spark: four long rays and a hot centre
n = 64 * S
spark = Image.new("L", (n, n), 0)
d = ImageDraw.Draw(spark)
c = n / 2
for a in (0, math.pi / 2, math.pi, 3 * math.pi / 2):
    tip = (c + math.cos(a) * 30 * S, c + math.sin(a) * 30 * S)
    l = (c + math.cos(a + math.pi / 2) * 4 * S, c + math.sin(a + math.pi / 2) * 4 * S)
    r = (c + math.cos(a - math.pi / 2) * 4 * S, c + math.sin(a - math.pi / 2) * 4 * S)
    d.polygon([tip, l, r], fill=255)
d.ellipse((c - 7 * S, c - 7 * S, c + 7 * S, c + 7 * S), fill=255)
spark = spark.filter(ImageFilter.GaussianBlur(1.5 * S))
save(spark, "fx-spark", (64, 64))

(DEST / "spell-fx-report.json").write_text(json.dumps(report, indent=2))
print("wrote", len(report), "textures")
