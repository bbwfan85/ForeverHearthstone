"""Import the nine classic heroes' voice lines; retain provenance.

Every line is taken from HearthSFX's own labelled hero entries (the bundle in
tools/hearthsfx-app.js), so which recording means "I need more mana" is read
from the source, never recalled. Attack and Death are already imported with
the card sounds (Client/Assets/CardSounds.lua) and are not repeated here.

Writes:
  ForeverHearthstone/Art/Sounds/Heroes/<recording>.wav
  ForeverHearthstone/Client/Assets/HeroVoice.lua
  ForeverHearthstone/Art/hero-voice-report.json   (source URL + sha256 per file)
"""
import ast
import concurrent.futures
import hashlib
import io
import json
import re
import urllib.parse
import urllib.request
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ForeverHearthstone/Art/Sounds/Heroes"
LUA = ROOT / "ForeverHearthstone/Client/Assets/HeroVoice.lua"
REPORT = ROOT / "ForeverHearthstone/Art/hero-voice-report.json"
SOURCE = "https://hearthstonesounds.s3.amazonaws.com/"
HEROES = ["HERO_%02d" % i for i in range(1, 10)]

# HearthSFX label -> the key the client asks for.
LABELS = {
    "Greetings": "greetings", "Well Played": "well_played", "Thanks": "thanks",
    "Sorry": "sorry", "Oops": "oops", "Threaten": "threaten", "Wow": "wow",
    "Concede": "concede", "Opening": "start", "Mirror Start": "mirror_start",
    "Greetings (Mirror)": "mirror_greetings", "Out of Time": "time",
    "Low on Cards": "low_cards", "Out of Cards": "no_cards",
    "Need Weapon": "need_weapon", "Mana": "mana",
    "Minion Attacked": "minion_attacked", "Hero Attacked": "hero_attacked",
    "Summon Sickness": "summon_sick", "Full Hand": "full_hand",
    "Too Many Minions": "full_board", "Stealth Minion": "stealth",
    "Can't Play": "cant_play", "Invalid Target": "target",
    "Taunt Minion": "taunt", "Generic": "generic",
    "Thinking (1)": "thinking1", "Thinking (2)": "thinking2",
    "Thinking (3)": "thinking3", "Picked in Arena": "picked",
    "Death": "death",
}


def load_heroes():
    source = (ROOT / "tools/hearthsfx-app.js").read_text(encoding="utf-8")
    cards = {}
    for match in re.finditer(r"JSON\.parse\(('(?:\\.|[^'\\])*')\)", source):
        try:
            entries = json.loads(ast.literal_eval(match.group(1)))
        except (ValueError, SyntaxError):
            continue
        if isinstance(entries, list):
            for card in entries:
                if isinstance(card, dict) and card.get("id") in HEROES:
                    cards[card["id"]] = card
    return cards


def local_name(recording):
    # Some recordings carry a space ("VO_HERO_01_Well Played_02"); WoW paths
    # are safer without one.
    return re.sub(r"[^\w.-]", "_", recording)


def fetch(recording):
    path = DEST / (local_name(recording) + ".wav")
    url = SOURCE + urllib.parse.quote(recording) + ".wav"
    try:
        data = path.read_bytes() if path.exists() else urllib.request.urlopen(url, timeout=30).read()
        with wave.open(io.BytesIO(data)) as w:
            params = w.getparams()
            if params.nframes == 0:
                raise ValueError("empty recording")
        path.write_bytes(data)
        return recording, {"source": url, "file": path.name,
                           "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data),
                           "channels": params.nchannels, "rate": params.framerate}
    except Exception as exc:  # recorded, never fatal: absent means silent
        return recording, {"source": url, "error": str(exc)}


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    heroes = load_heroes()
    missing = [h for h in HEROES if h not in heroes]
    if missing:
        raise SystemExit("HearthSFX bundle lacks: " + ", ".join(missing))
    wanted = {}
    for hero in HEROES:
        for entry in heroes[hero]["sounds"]:
            key = LABELS.get(entry.get("name"))
            audio = entry.get("audio")
            if key and isinstance(audio, str) and key not in wanted.setdefault(hero, {}):
                wanted[hero][key] = audio
    jobs = sorted({a for lines in wanted.values() for a in lines.values()})
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        results = dict(pool.map(fetch, jobs))

    lines = ["-- Generated by tools/import_hero_voice.py from HearthSFX's labelled hero",
             "-- entries. Provenance: Art/hero-voice-report.json. Absent means silent.",
             "local _, ns = ...", "ns.HeroVoice = {"]
    for hero in HEROES:
        fields = ["%s=%s" % (key, json.dumps(results[a]["file"][:-4]))
                  for key, a in sorted(wanted[hero].items()) if "error" not in results[a]]
        lines.append('  ["%s"]={%s},' % (hero, ",".join(fields)))
    lines.append("}")
    LUA.write_text("\n".join(lines) + "\n", encoding="utf-8")
    REPORT.write_text(json.dumps({"heroes": wanted, "audio": results}, indent=2) + "\n", encoding="utf-8")
    failed = [a for a, r in results.items() if "error" in r]
    print(f"Hero voice: {len(jobs) - len(failed)}/{len(jobs)} recordings; failed: {failed}")


if __name__ == "__main__":
    main()
