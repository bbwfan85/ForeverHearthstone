"""Generated textures for the match screen (docs/12).

Run with the bundled Python + Pillow runtime. Everything here is original
procedural artwork -- there is no source asset for any of it -- drawn in the
Hearthstone manner: gilded rims, dark stone, warm glows. Output goes to
ForeverHearthstone/Art as uncompressed TGA; provenance to
Art/match-assets-report.json.

  resize-grip        three gilded ridges for the bottom-right resize corner
  mute-on/-off       the board's speaker button
  turn-banner        the "Your Turn" medallion: stone lozenge, gold rim, wings
  emote-plaque       one speech plaque of the emote wheel
  arrow-seg          one chevron of the targeting arrow's body
  arrow-head         the targeting arrow's head
  target-ring        the crosshair ring over a legal target
  hero-crack         cracks spreading across a dying hero's portrait
  fx-<school>        spell sprites: flame, frost, arcane, holy, shadow, nature,
                     lightning, and a plain soft orb
"""
from pathlib import Path
import json, math, random

from PIL import Image, ImageDraw, ImageFilter, ImageChops

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ForeverHearthstone" / "Art"
report = {}

GOLD_HI, GOLD, GOLD_LO, BRONZE = (255, 238, 160), (224, 172, 72), (150, 96, 30), (70, 42, 14)


def save(im, name, size=None):
    if size:
        im = im.resize(size, Image.Resampling.LANCZOS)
    im.save(DEST / (name + ".tga"))
    report[name] = {"source": "generated by tools/build_match_assets.py",
                    "provenance": "original procedural artwork", "texture_size": im.size}


def vgrad(size, top, bottom):
    w, h = size
    col = Image.new("RGBA", (1, h))
    for y in range(h):
        t = y / max(1, h - 1)
        col.putpixel((0, y), tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(4)))
    return col.resize(size)


def radial(size, color, power=1.6):
    w, h = size
    im = Image.new("RGBA", size)
    px = im.load()
    for y in range(h):
        for x in range(w):
            d = math.hypot((x - w / 2 + .5) / (w / 2), (y - h / 2 + .5) / (h / 2))
            px[x, y] = color[:3] + (round(color[3] * max(0, 1 - d) ** power),)
    return im


def masked(fill, mask):
    out = fill.copy()
    out.putalpha(ImageChops.multiply(fill.getchannel("A"), mask))
    return out


def rrect(size, box, radius):
    m = Image.new("L", size, 0)
    ImageDraw.Draw(m).rounded_rectangle(box, radius=radius, fill=255)
    return m


def ellipse(size, box):
    m = Image.new("L", size, 0)
    ImageDraw.Draw(m).ellipse(box, fill=255)
    return m


def polygon(size, pts):
    m = Image.new("L", size, 0)
    ImageDraw.Draw(m).polygon(pts, fill=255)
    return m


def grow(mask, px):
    return mask.filter(ImageFilter.MaxFilter(px * 2 + 1))


def shrink(mask, px):
    return mask.filter(ImageFilter.MinFilter(px * 2 + 1))


def gilded(mask, size, rim=6):
    """A gold bevel following `mask`'s edge: dark outline, bright top-lit gold."""
    out = Image.new("RGBA", size)
    outline = ImageChops.subtract(grow(mask, 2), shrink(mask, rim))
    out.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (255,)), outline))
    gold = vgrad(size, GOLD_HI + (255,), GOLD_LO + (255,))
    ring = ImageChops.subtract(mask, shrink(mask, rim))
    out.alpha_composite(masked(gold, ring))
    inner = ImageChops.subtract(shrink(mask, rim), shrink(mask, rim + 2))
    out.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (220,)), inner))
    return out


S = 4  # supersample factor for crisp edges

# ------------------------------------------------------------- resize grip
size = (64 * S, 64 * S)
grip = Image.new("RGBA", size)
for k in (20, 36, 52):
    line = Image.new("L", size, 0)
    d = ImageDraw.Draw(line)
    d.line([(size[0] - k * S, size[1] - 3 * S), (size[0] - 3 * S, size[1] - k * S)], fill=255, width=6 * S)
    grip.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (255,)), grow(line, 2 * S)))
    grip.alpha_composite(masked(vgrad(size, GOLD_HI + (255,), GOLD + (255,)), line))
save(grip, "resize-grip", (64, 64))

# ------------------------------------------------------------- mute button
for state in ("on", "off"):
    size = (64 * S, 64 * S)
    im = Image.new("RGBA", size)
    disc = ellipse(size, (4 * S, 4 * S, 60 * S, 60 * S))
    im.alpha_composite(masked(vgrad(size, (70, 50, 34, 255), (26, 18, 12, 255)), disc))
    im.alpha_composite(gilded(disc, size, 4 * S))
    glyph = polygon(size, [(18 * S, 26 * S), (26 * S, 26 * S), (36 * S, 17 * S),
                           (36 * S, 47 * S), (26 * S, 38 * S), (18 * S, 38 * S)])
    cream = Image.new("RGBA", size, (255, 244, 214, 255))
    im.alpha_composite(masked(cream, glyph))
    marks = Image.new("L", size, 0)
    d = ImageDraw.Draw(marks)
    if state == "on":
        for r in (8, 14):
            d.arc((34 * S - r * S, 32 * S - r * S, 34 * S + r * S, 32 * S + r * S), -50, 50, fill=255, width=3 * S)
        im.alpha_composite(masked(cream, marks))
    else:
        d.line([(40 * S, 24 * S), (52 * S, 40 * S)], fill=255, width=4 * S)
        d.line([(52 * S, 24 * S), (40 * S, 40 * S)], fill=255, width=4 * S)
        im.alpha_composite(masked(Image.new("RGBA", size, (230, 60, 40, 255)), marks))
    save(im, "mute-" + state, (64, 64))

# ------------------------------------------------------------- close cross
# The board's close button draws this rather than a letter "X": a font glyph
# is centred by its line box (ascender and descender), not by its ink, so it
# never sat in the middle of the round button. Cream bars, bronze outline,
# symmetric about the texture's centre.
size = (64 * S, 64 * S)
cross = Image.new("L", size, 0)
d = ImageDraw.Draw(cross)
for a, b in (((18, 18), (46, 46)), ((46, 18), (18, 46))):
    d.line([(a[0] * S, a[1] * S), (b[0] * S, b[1] * S)], fill=255, width=7 * S)
im = Image.new("RGBA", size)
im.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (255,)), grow(cross, 2 * S)))
im.alpha_composite(masked(vgrad(size, (255, 246, 222, 255), (238, 214, 168, 255)), cross))
save(im, "close-x", (64, 64))

# ------------------------------------------------------------- turn banner
# Hearthstone announces your turn in big gold lettering floating over the
# table, not on a badge. The old medallion here (a flat vector pill with
# gilded wings and a gem) read as UI pasted onto painted art. What remains is
# only what the lettering needs to read on any board: a soft, feathered haze
# behind it, and two fine gold rules above and below that fade out at the
# ends. The words themselves are drawn by the client (Board.banner.text).
W, H = 512 * 2, 256 * 2
size = (W, H)
banner = Image.new("RGBA", size)
haze = radial((W, H), (8, 6, 4, 190), 1.15)
banner.alpha_composite(haze)
for y in (H * .27, H * .73):
    rule = Image.new("L", size, 0)
    ImageDraw.Draw(rule).line([(W * .14, y), (W * .86, y)], fill=255, width=5)
    rule = rule.filter(ImageFilter.GaussianBlur(1.2))
    # fade toward both ends
    fade = Image.linear_gradient("L").rotate(90, expand=True).resize((W // 2, 1))
    fade = Image.merge("L", [fade]).resize((W // 2, H))
    ramp = Image.new("L", size, 0)
    ramp.paste(fade, (0, 0)); ramp.paste(fade.transpose(Image.FLIP_LEFT_RIGHT), (W // 2, 0))
    rule = ImageChops.multiply(rule, ramp)
    shadow = rule.filter(ImageFilter.GaussianBlur(4))
    banner.alpha_composite(masked(Image.new("RGBA", size, (0, 0, 0, 200)), shadow))
    banner.alpha_composite(masked(vgrad(size, GOLD_HI + (255,), GOLD + (255,)), rule))
    # a small diamond at the centre of each rule
    gem = polygon(size, [(W / 2, y - 12), (W / 2 + 18, y), (W / 2, y + 12), (W / 2 - 18, y)])
    banner.alpha_composite(masked(Image.new("RGBA", size, BRONZE + (255,)), grow(gem, 2)))
    banner.alpha_composite(masked(vgrad(size, GOLD_HI + (255,), GOLD_LO + (255,)), gem))
save(banner, "turn-banner", (512, 256))

# ------------------------------------------------------------- emote plaque
size = (256 * S, 80 * S)
plaque = Image.new("RGBA", size)
shape = rrect(size, (4 * S, 6 * S, 252 * S, 74 * S), 30 * S)
plaque.alpha_composite(masked(vgrad(size, (255, 250, 232, 255), (226, 208, 170, 255)), shape))
plaque.alpha_composite(gilded(shape, size, 5 * S))
save(plaque, "emote-plaque", (256, 80))

# ------------------------------------------------------------- targeting arrow
# The body is a chain of chevrons pointing UP (the client rotates each one to
# the curve's tangent); the head is a broad barbed point, also pointing up.
size = (64 * S, 64 * S)
chev = polygon(size, [(8 * S, 50 * S), (32 * S, 18 * S), (56 * S, 50 * S),
                      (46 * S, 56 * S), (32 * S, 36 * S), (18 * S, 56 * S)])
seg = Image.new("RGBA", size)
seg.alpha_composite(masked(Image.new("RGBA", size, (60, 8, 4, 255)), grow(chev, 2 * S)))
seg.alpha_composite(masked(vgrad(size, (255, 214, 120, 255), (230, 60, 20, 255)), chev))
save(seg, "arrow-seg", (64, 64))

size = (128 * S, 128 * S)
head = polygon(size, [(64 * S, 6 * S), (118 * S, 92 * S), (78 * S, 78 * S), (64 * S, 122 * S),
                      (50 * S, 78 * S), (10 * S, 92 * S)])
arrowhead = Image.new("RGBA", size)
arrowhead.alpha_composite(masked(radial(size, (255, 90, 30, 170), 1.2), grow(head, 10 * S)))
arrowhead.alpha_composite(gilded(head, size, 6 * S))
arrowhead.alpha_composite(masked(vgrad(size, (255, 150, 70, 255), (190, 20, 10, 255)), shrink(head, 6 * S)))
save(arrowhead, "arrow-head", (128, 128))

ring = Image.new("RGBA", size)
outer = ellipse(size, (10 * S, 10 * S, 118 * S, 118 * S))
band = ImageChops.subtract(outer, ellipse(size, (26 * S, 26 * S, 102 * S, 102 * S)))
ticks = Image.new("L", size, 0)
d = ImageDraw.Draw(ticks)
for ang in (0, 90, 180, 270):
    a = math.radians(ang)
    d.line([(64 * S + math.cos(a) * 30 * S, 64 * S + math.sin(a) * 30 * S),
            (64 * S + math.cos(a) * 60 * S, 64 * S + math.sin(a) * 60 * S)], fill=255, width=7 * S)
shape = ImageChops.lighter(band, ticks)
ring.alpha_composite(masked(Image.new("RGBA", size, (60, 6, 2, 255)), grow(shape, 2 * S)))
ring.alpha_composite(masked(vgrad(size, (255, 200, 110, 255), (220, 40, 16, 255)), shape))
save(ring, "target-ring", (128, 128))

# ------------------------------------------------------------- hero crack
random.seed(7)
size = (512, 512)
crack = Image.new("L", size, 0)
d = ImageDraw.Draw(crack)
for i in range(11):
    ang = i / 11 * math.tau + random.uniform(-.2, .2)
    x, y, width = 256, 256, 9
    for _ in range(9):
        ang += random.uniform(-.45, .45)
        step = random.uniform(22, 38)
        nx, ny = x + math.cos(ang) * step, y + math.sin(ang) * step
        d.line([(x, y), (nx, ny)], fill=255, width=max(2, round(width)))
        if random.random() < .35:
            b = ang + random.choice((-1, 1)) * random.uniform(.6, 1.1)
            d.line([(nx, ny), (nx + math.cos(b) * 30, ny + math.sin(b) * 30)], fill=255, width=2)
        x, y, width = nx, ny, width * .8
cracked = Image.new("RGBA", size)
cracked.alpha_composite(masked(Image.new("RGBA", size, (255, 210, 120, 200)), grow(crack, 3).filter(ImageFilter.GaussianBlur(3))))
cracked.alpha_composite(masked(Image.new("RGBA", size, (20, 10, 4, 255)), crack))
save(cracked, "hero-crack", (256, 256))

# ------------------------------------------------------------- spell sprites
# Coloured in the texture itself so the client can draw them ADD without tint.
SCHOOL = {"fire": (255, 130, 30), "frost": (120, 200, 255), "arcane": (200, 110, 255),
          "holy": (255, 230, 140), "shadow": (150, 60, 210), "nature": (110, 230, 90),
          "lightning": (150, 200, 255), "orb": (255, 255, 255)}
size = (128 * S, 128 * S)
for school, rgb in SCHOOL.items():
    im = radial(size, rgb + (200,), 1.8)
    core = Image.new("L", size, 0)
    d = ImageDraw.Draw(core)
    c = 64 * S
    if school == "fire":
        d.polygon([(c, 14 * S), (c + 30 * S, 70 * S), (c + 22 * S, 100 * S), (c, 112 * S),
                   (c - 22 * S, 100 * S), (c - 30 * S, 70 * S)], fill=255)
    elif school == "frost":
        d.polygon([(c, 10 * S), (c + 18 * S, 64 * S), (c, 118 * S), (c - 18 * S, 64 * S)], fill=255)
        d.polygon([(10 * S, c), (c, c - 14 * S), (118 * S, c), (c, c + 14 * S)], fill=160)
    elif school == "holy":
        for k in range(8):
            a = k / 8 * math.tau
            d.polygon([(c + math.cos(a) * 58 * S, c + math.sin(a) * 58 * S),
                       (c + math.cos(a + .25) * 14 * S, c + math.sin(a + .25) * 14 * S),
                       (c + math.cos(a - .25) * 14 * S, c + math.sin(a - .25) * 14 * S)], fill=255)
    elif school == "nature":
        d.ellipse((c - 18 * S, 16 * S, c + 18 * S, 112 * S), fill=255)
    elif school == "lightning":
        d.line([(c - 10 * S, 8 * S), (c + 14 * S, 48 * S), (c - 12 * S, 70 * S), (c + 10 * S, 120 * S)],
               fill=255, width=9 * S)
    elif school == "shadow":
        for k in range(3):
            d.arc((c - (44 - k * 12) * S, c - (44 - k * 12) * S, c + (44 - k * 12) * S, c + (44 - k * 12) * S),
                  k * 110, k * 110 + 200, fill=255, width=8 * S)
    else:  # arcane / orb
        d.ellipse((c - 24 * S, c - 24 * S, c + 24 * S, c + 24 * S), fill=255)
    core = core.filter(ImageFilter.GaussianBlur(3 * S))
    hot = tuple(min(255, v + 120) for v in rgb)
    im.alpha_composite(masked(Image.new("RGBA", size, hot + (255,)), core))
    save(im, "fx-" + school, (128, 128))

(DEST / "match-assets-report.json").write_text(json.dumps(report, indent=2))
print("wrote", len(report), "textures")
